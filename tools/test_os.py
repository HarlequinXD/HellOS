import asyncio, sys, subprocess, time, os
from playwright.async_api import async_playwright
WWW = sys.argv[1]
OUT = 'shots'
import os; os.makedirs(OUT, exist_ok=True)
errors = []
async def main():
    srv = subprocess.Popen([sys.executable, '-m', 'http.server', '8666', '--bind', '127.0.0.1'], cwd=WWW, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(1)
    try:
        async with async_playwright() as p:
            b = await p.chromium.launch( args=['--no-sandbox','--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream','--autoplay-policy=no-user-gesture-required'])
            ctx = await b.new_context(viewport={'width': 412, 'height': 892}, has_touch=False, permissions=['camera','microphone'])
            pg = await ctx.new_page()
            pg.set_default_timeout(8000)
            await ctx.route('**/fonts.googleapis.com/**', lambda r: r.abort())
            await ctx.route('**/fonts.gstatic.com/**', lambda r: r.abort())
            pg.on('console', lambda m: errors.append('console.' + m.type + ': ' + m.text) if m.type in ('error','warning') else None)
            pg.on('pageerror', lambda e: errors.append('PAGEERROR: ' + str(e)))
            print('STEP', "await pg.goto('http://127.0.0.1:8666/index.html')", flush=True)
            await pg.goto('http://127.0.0.1:8666/index.html')
            await pg.wait_for_timeout(3800)
            await pg.screenshot(path=OUT+'/01_setup_welcome.png')
            print('STEP', "await pg.click('text=Begin descent')", flush=True)
            await pg.click('text=Begin descent')
            print('STEP', "await pg.click('text=Hellnet 666')", flush=True)
            await pg.click('text=Hellnet 666')
            print('STEP', "await pg.fill('.dialog input', 'abc')", flush=True)
            await pg.fill('.dialog input', 'abc')
            print('STEP', "await pg.click('.dialog >> text=Connect')", flush=True)
            await pg.click('.dialog >> text=Connect')
            await pg.wait_for_timeout(1600)
            await pg.screenshot(path=OUT+'/02_setup_net.png')
            print('STEP', 'await pg.click(\'button.btn:has-text("Next")\')', flush=True)
            await pg.click('button.btn:has-text("Next")')
            # sign
            box = await pg.locator('canvas.sigpad').bounding_box()
            await pg.mouse.move(box['x']+20, box['y']+40); await pg.mouse.down()
            for i in range(40):
                await pg.mouse.move(box['x']+20+i*7, box['y']+40+(i%5)*15)
            await pg.mouse.up()
            await pg.screenshot(path=OUT+'/03_setup_terms.png')
            print('STEP', "await pg.click('text=Sign & accept')", flush=True)
            await pg.click('text=Sign & accept')
            print('STEP', 'await pg.fill(\'input[placeholder="e.g. Morgana Vale"]\', \'Harley Quinn\'', flush=True)
            await pg.fill('input[placeholder="e.g. Morgana Vale"]', 'Harley Quinn')
            print('STEP', "await pg.fill('input[type=password]', 'hellpass')", flush=True)
            await pg.fill('input[type=password]', 'hellpass')
            print('STEP', "await pg.click('text=Create pact')", flush=True)
            await pg.click('text=Create pact')
            print('STEP', "await pg.click('text=Blood PIN')", flush=True)
            await pg.click('text=Blood PIN')
            for k in '6666': await pg.click(f'.pinpad .keypad button:has-text("{k}")')
            print('STEP', "await pg.click('.pinpad [aria-label=Enter]')", flush=True)
            await pg.click('.pinpad [aria-label=Enter]')
            for k in '6666': await pg.click(f'.pinpad .keypad button:has-text("{k}")')
            print('STEP', "await pg.click('.pinpad [aria-label=Enter]')", flush=True)
            await pg.click('.pinpad [aria-label=Enter]')
            await pg.screenshot(path=OUT+'/04_setup_lock.png')
            print('STEP', 'await pg.click(\'button.btn:has-text("Next")\')', flush=True)
            await pg.click('button.btn:has-text("Next")')
            await pg.screenshot(path=OUT+'/05_setup_theme.png')
            print('STEP', 'await pg.click(\'button.btn:has-text("Next")\')', flush=True)
            await pg.click('button.btn:has-text("Next")')
            print('STEP', "await pg.click('text=Accept')", flush=True)
            await pg.click('text=Accept')
            print('STEP', "await pg.click('text=Enter HellOS')", flush=True)
            await pg.click('text=Enter HellOS')
            await pg.wait_for_timeout(2500)
            await pg.screenshot(path=OUT+'/06_home.png')
            # drawer
            await pg.evaluate('Home.openDrawer()'); await pg.wait_for_timeout(400)
            await pg.screenshot(path=OUT+'/07_drawer.png')
            await pg.evaluate('Home.closeDrawer()')
            await pg.evaluate('Shade.open()'); await pg.wait_for_timeout(400)
            await pg.screenshot(path=OUT+'/08_shade.png')
            await pg.evaluate('Shade.close(true)')
            # lock + unlock
            await pg.evaluate('Lock.lock(true)'); await pg.wait_for_timeout(300)
            await pg.screenshot(path=OUT+'/09_lock.png')
            print('STEP', "await pg.click('.seal-btn')", flush=True)
            await pg.click('.seal-btn')
            for k in '6666': await pg.click(f'.pinpad .keypad button:has-text("{k}")')
            await pg.wait_for_timeout(600)
            locked = await pg.evaluate('OS.locked')
            print('locked after pin:', locked)
            apps = await pg.evaluate("Object.values(OS.apps).filter(a=>!a.store).map(a=>a.id)")
            for i, a in enumerate(apps):
                await pg.evaluate(f"OS.open('{a}')"); await pg.wait_for_timeout(900)
                await pg.screenshot(path=f'{OUT}/app_{a}.png')
                await pg.evaluate("OS.home()"); await pg.wait_for_timeout(300)
            # store installs
            await pg.evaluate("Store.setting('souls', 500)")
            store = await pg.evaluate("Object.keys(CATALOG)")
            await pg.evaluate("OS.open('hellplay')"); await pg.wait_for_timeout(500)
            for s in store:
                await pg.evaluate(f"void HellPlay.install('{s}')"); await pg.wait_for_timeout(300)
                # accept purchase dialog if any
                if await pg.locator('.dialog').count():
                    print('STEP', "await pg.click('.dialog .btn >> nth=-1')", flush=True)
                    await pg.click('.dialog .btn >> nth=-1')
            await pg.wait_for_timeout(8000)
            inst = await pg.evaluate("Object.keys(Store.get('installed',{}))")
            print('installed:', inst)
            await pg.screenshot(path=OUT+'/store_after.png')
            for s in store:
                await pg.evaluate(f"OS.open('{s}')"); await pg.wait_for_timeout(900)
                await pg.screenshot(path=f'{OUT}/store_{s}.png')
                await pg.evaluate("OS.home()"); await pg.wait_for_timeout(200)
            await pg.screenshot(path=OUT+'/home_after.png')
            await b.close()
    finally:
        srv.terminate()
asyncio.run(main())
print('ERRORS:', len(errors))
for e in errors[:60]: print(e)
